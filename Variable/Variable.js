// Example using let
let x = 5;
let y = 6;
let z = x + y;
console.log(z) //11

// Example using const : Always use const if the value should not be changed

const xx = 55;
const yy = 62;
const zz = xx + yy;
console.log(zz) //117

// Declaring a Variable Using var

var A = 15;
var B = 56;
var C = A + B;
console.log(C);//71

// Declaring a Variable Automatically : Undeclared variables are automatically declared when first used:
M = 59;
N = 91;
P = M + N;
console.log(P); //150